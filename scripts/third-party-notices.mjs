// Generates THIRD_PARTY_NOTICES.txt: the licence text and copyright notice of every production
// (shipped) dependency, including the self-hosted fonts (OFL-1.1). Most open-source licences
// require shipping these with the software (compliance.md section 3). The web image serves it
// at /third-party-notices.txt; the server image contains it at /app/THIRD_PARTY_NOTICES.txt.
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  fail if the file is missing or out of date
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUTPUT = 'THIRD_PARTY_NOTICES.txt';
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$|^ofl\.txt$/i;

// Fixed command string (no user input), run through the shell so pnpm resolves on Windows too.
const byLicense = JSON.parse(
  execSync('pnpm -r licenses list --prod --json', {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }),
);

/** Packages built for one operating system / CPU (e.g. @esbuild/win32-x64). */
function isPlatformBinary(dir) {
  try {
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    return Array.isArray(manifest.os) || Array.isArray(manifest.cpu);
  } catch {
    return false;
  }
}

const packages = [];
for (const [license, entries] of Object.entries(byLicense)) {
  for (const entry of entries) {
    const dir = entry.paths?.find((p) => existsSync(p));
    // Covered by their main package's entry (same project and licence); skipping them keeps the
    // file identical on Windows, macOS and Linux.
    if (dir && isPlatformBinary(dir)) continue;
    const files = dir
      ? readdirSync(dir)
          .filter((f) => LICENSE_FILE.test(f))
          .sort()
      : [];
    const texts = files.map((f) =>
      readFileSync(join(dir, f), 'utf8').replace(/\r\n?/g, '\n').trim(),
    );
    packages.push({
      name: entry.name,
      versions: [...entry.versions].sort(),
      license,
      homepage: entry.homepage ?? '',
      author: typeof entry.author === 'string' ? entry.author : (entry.author?.name ?? ''),
      texts,
    });
  }
}
packages.sort((a, b) => a.name.localeCompare(b.name, 'en'));

const rule = '-'.repeat(78);
const lines = [
  'THIRD-PARTY SOFTWARE NOTICES',
  '',
  'Ultimate ERP includes the following open-source software. Each component is provided under',
  'its own licence, reproduced below. Generated by scripts/third-party-notices.mjs; do not edit.',
  'Platform-specific binary builds (e.g. @esbuild/<platform>) are covered by the entry of',
  'their main package.',
  '',
  `Components: ${packages.length}`,
  '',
];
for (const pkg of packages) {
  lines.push(rule, `${pkg.name} ${pkg.versions.join(', ')}`, `Licence: ${pkg.license}`);
  if (pkg.author) lines.push(`Author: ${pkg.author}`);
  if (pkg.homepage) lines.push(`Homepage: ${pkg.homepage}`);
  lines.push('');
  if (pkg.texts.length === 0) {
    lines.push(
      `(No licence file is included in this package; it is published under ${pkg.license}.)`,
    );
  } else {
    lines.push(...pkg.texts.join('\n\n').split('\n'));
  }
  lines.push('');
}
const output = `${lines.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n?/g, '\n') : '';
  if (current !== output) {
    console.error(`${OUTPUT} is missing or out of date. Run: pnpm notices`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date (${packages.length} components).`);
} else {
  writeFileSync(OUTPUT, output);
  const missing = packages.filter((p) => p.texts.length === 0).length;
  console.log(
    `Wrote ${OUTPUT}: ${packages.length} components (${missing} without a licence file).`,
  );
}
